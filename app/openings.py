BOOK = {tuple(line.split()): name for line, name in _LINES.items()}
# Усі початкові відрізки довідкових варіантів теж вважаємо теорією.
_PREFIXES = {line[:i] for line in BOOK for i in range(1, len(line) + 1)}


def opening_name(sans: list[str]) -> str | None:
    for n in range(min(len(sans), 8), 0, -1):
        name = BOOK.get(tuple(sans[:n]))
        if name:
            return name
    return None


def book_plies(sans: list[str]) -> int:
    """Скільки перших півходів збігаються з довідником."""
    n = 0
    while n < len(sans) and tuple(sans[:n + 1]) in _PREFIXES:
        n += 1
    return n
